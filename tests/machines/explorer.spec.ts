import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('catalog filters, unknown memory, URL round trip and reset', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/Machines')
  await expect(page.locator('.machine-card')).toHaveCount(10)
  await page.getByRole('combobox', { name: 'Platform', exact: true }).selectOption('HGX')
  await expect(page.locator('.machine-card')).toHaveCount(2)
  await expect(page).toHaveURL(/platform=HGX/)
  await page.getByRole('combobox', { name: 'Minimum primary GPU memory' }).selectOption('180')
  await expect(page.locator('.machine-card')).toHaveCount(1)
  await expect(page.locator('.machine-card h3')).toHaveText('NVIDIA HGX B200')
  await page.reload()
  await expect(page.locator('.machine-card')).toHaveCount(1)
  await expect(page.getByRole('combobox', { name: 'Platform', exact: true })).toHaveValue('HGX')
  await page.getByRole('button', { name: 'Reset filters' }).click()
  await expect(page.locator('.machine-card')).toHaveCount(10)
  await page.getByLabel('Search configurations').fill('no such configuration')
  await expect(page.getByText('No configurations match yet.')).toBeVisible()
  await page.getByRole('button', { name: 'Show all machines' }).click()
  await expect(page.locator('.machine-card')).toHaveCount(10)
  await page.getByRole('combobox', { name: 'Sort by' }).selectOption('memory')
  await expect(page.locator('.machine-card h3').first()).toHaveText('NVIDIA GB300-based Workstation')
  expect(errors).toEqual([])
})

test('selection stays local, persists, compares and exports only presentation data', async ({ page }) => {
  const writes: string[] = []
  page.on('request', req => { if (req.method() !== 'GET') writes.push(`${req.method()} ${req.url()}`) })
  await page.goto('/Machines')
  await page.getByRole('button', { name: 'Select NVIDIA HGX B300', exact: true }).click()
  await page.getByRole('button', { name: 'Select NVIDIA GB300-based Workstation', exact: true }).click()
  await expect(page).toHaveURL(/select=hgx-b300%2Cgb300-tower/)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Remove NVIDIA HGX B300', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Compare & save' }).click()
  await expect(page.getByRole('heading', { name: 'The details, side by side.' })).toBeFocused()
  await expect(page.getByRole('table')).toContainText('GPU memory requires confirmation')
  await expect(page.getByRole('table')).toContainText('1 × NVIDIA B300; 1 × NVIDIA RTX PRO 4000')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download summary' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('zipcode-machine-selection.md')
  const path = await download.path()
  const summary = await readFile(path!, 'utf8')
  expect(summary).toContain('NVIDIA HGX B300')
  expect(summary).toContain('Storage drive layout and RAID configuration require confirmation')
  expect(summary).toContain('Request quote')
  expect(summary).not.toMatch(/https?:\/\/|mailto:|\$\d|quote[_-]?id|bank/i)
  expect(writes).toEqual([])
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
  await expect(page.getByText('No machines selected yet.')).toBeVisible()
})

