test('shared selected view and explicit empty selection override saved browser state', async ({ page }) => {
  await page.goto('/Machines?view=selected&select=hgx-b300')
  await expect(page.getByRole('button', { name: 'Selected (1)', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.machine-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
  await page.evaluate(() => {
    Object.defineProperty(navigator, 'clipboard', { value: { writeText: async (text: string) => { (window as unknown as { copiedView: string }).copiedView = text } }, configurable: true })
  })
  await page.getByRole('button', { name: 'Copy view link' }).click()
  const shared = await page.evaluate(() => (window as unknown as { copiedView: string }).copiedView)
  expect(shared).toContain('select=')
  expect(shared).toContain('view=selected')
  await page.evaluate(() => localStorage.setItem('zipcode-machine-selection-v1', JSON.stringify(['hgx-b200'])))
  await page.goto(shared)
  await expect(page.getByRole('button', { name: 'Selected (0)', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByText('Your selection starts here.')).toBeVisible()
})

test('GPU-count filter, active chips, detail deep link and lowercase detail redirect', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/Machines')
  await page.getByRole('combobox', { name: 'Primary GPU count' }).selectOption('72')
  await expect(page.locator('.machine-card')).toHaveCount(3)
  await expect(page).toHaveURL(/gpus=72/)
  await page.getByRole('combobox', { name: 'Platform', exact: true }).selectOption('DGX')
  await expect(page.getByRole('list', { name: 'Active filters' }).getByRole('button')).toHaveCount(3)
  await page.getByRole('button', { name: 'Remove filter 72 primary GPUs' }).click()
  await expect(page.locator('.machine-card')).toHaveCount(6)
  await page.getByRole('button', { name: 'Clear all' }).click()
  await expect(page.locator('.machine-card')).toHaveCount(10)
  await expect(page.locator('.machine-card .card-kicker').first()).toHaveText(/NVIDIA HGX platform server/)
  await expect(page.locator('.machine-card .card-kicker')).not.toContainText(['Zipcode'])

  await page.locator('.machine-card').filter({ hasText: 'NVIDIA HGX B300' }).getByRole('link', { name: /View full configuration/ }).click()
  await expect(page).toHaveURL(/\/Machines\/hgx-b300$/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('NVIDIA HGX B300')
  await expect(page.getByText('GPU memory requires confirmation')).toBeVisible()
  await expect(page.getByText('Request quote')).toBeVisible()
  await page.getByRole('button', { name: 'Select NVIDIA HGX B300', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Remove NVIDIA HGX B300', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('link', { name: /Compare your selection \(1\)/ }).click()
  await expect(page.locator('.machine-comparison')).toContainText('NVIDIA HGX B300')

  await page.goto('/machines/dgx-b300')
  await expect(page).toHaveURL(/\/Machines\/dgx-b300$/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('NVIDIA DGX B300')
  const missing = await page.goto('/Machines/not-a-machine')
  expect(missing?.status()).toBe(404)
  expect(errors).toEqual([])
})

test('comparison is capped at four systems and the summary can be copied', async ({ page }) => {
  await page.goto('/Machines')
  for (const name of ['NVIDIA HGX B300', 'NVIDIA HGX B200', 'NVIDIA H200 NVL', 'NVIDIA DGX B300']) {
    await page.getByRole('button', { name: `Select ${name}`, exact: true }).click()
  }
  await page.getByRole('button', { name: 'Select NVIDIA DGX B200', exact: true }).click()
  await expect(page.locator('.machine-notice')).toContainText('Compare up to 4 configurations')
  await expect(page.getByRole('button', { name: 'Select NVIDIA DGX B200', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await page.evaluate(() => {
    Object.defineProperty(navigator, 'clipboard', { value: { writeText: async (text: string) => { (window as unknown as { copied: string }).copied = text } }, configurable: true })
  })
  await page.getByRole('button', { name: 'Copy summary' }).click()
  const copied = await page.evaluate(() => (window as unknown as { copied: string }).copied)
  expect(copied).toContain('# Zipcode machine selection')
  expect(copied.match(/^## /gm)?.length).toBe(4)
  expect(copied).not.toMatch(/https?:\/\/|mailto:|\$\d|quote[_-]?id/i)
})

